//! Stage 1 — finding what needs support: overhanging faces, the connected
//! regions they form, and islands (a slice of the model that has nothing
//! underneath it).

use std::collections::HashMap;
use std::sync::atomic::{AtomicBool, Ordering};

use rayon::prelude::*;

use super::config::SupportConfig;
use crate::mesh::{Mesh, Vec3};
use crate::slicer;

/// Every triangle of every mesh in one list, with the corners welded so that
/// triangles that share a corner can be found next to each other.
pub struct Faces {
    pub tris: Vec<[Vec3; 3]>,
    pub normals: Vec<Vec3>,
    pub areas: Vec<f32>,
    /// Source mesh for every triangle, so contacts from different pieces are
    /// never routed into the same support tree.
    pub model_ids: Vec<usize>,
    /// Welded corner ids per triangle, and the corner positions by id.
    pub ids: Vec<[u32; 3]>,
    pub verts: Vec<Vec3>,
}

impl Faces {
    pub fn new(meshes: &[Mesh]) -> Self {
        let mut tris = Vec::new();
        let mut model_ids = Vec::new();
        let mut ids = Vec::new();
        let mut verts: Vec<Vec3> = Vec::new();
        let mut weld: HashMap<(i64, i64, i64), u32> = HashMap::new();
        let mut id_of = |p: Vec3, verts: &mut Vec<Vec3>| -> u32 {
            let key = (
                (p.x * 1000.0).round() as i64,
                (p.y * 1000.0).round() as i64,
                (p.z * 1000.0).round() as i64,
            );
            match weld.get(&key) {
                Some(v) => *v,
                None => {
                    let v = verts.len() as u32;
                    verts.push(p);
                    weld.insert(key, v);
                    v
                }
            }
        };
        for (model_id, m) in meshes.iter().enumerate() {
            for t in &m.tris {
                let [a, b, c] = m.tri_verts(*t);
                if !finite(a) || !finite(b) || !finite(c) {
                    continue;
                }
                if (b - a).cross(c - a).length() < 1e-12 {
                    continue;
                }
                tris.push([a, b, c]);
                model_ids.push(model_id);
                ids.push([
                    id_of(a, &mut verts),
                    id_of(b, &mut verts),
                    id_of(c, &mut verts),
                ]);
            }
        }
        let normals: Vec<Vec3> = tris.iter().map(|t| normal(*t)).collect();
        let areas: Vec<f32> = tris
            .iter()
            .map(|t| (t[1] - t[0]).cross(t[2] - t[0]).length() * 0.5)
            .collect();
        Self {
            tris,
            normals,
            areas,
            model_ids,
            ids,
            verts,
        }
    }

    pub fn len(&self) -> usize {
        self.tris.len()
    }

    pub fn is_empty(&self) -> bool {
        self.tris.is_empty()
    }

    pub fn centroid(&self, i: u32) -> Vec3 {
        let t = self.tris[i as usize];
        (t[0] + t[1] + t[2]) * (1.0 / 3.0)
    }
}

fn finite(v: Vec3) -> bool {
    v.x.is_finite() && v.y.is_finite() && v.z.is_finite()
}

fn normal(t: [Vec3; 3]) -> Vec3 {
    let n = (t[1] - t[0]).cross(t[2] - t[0]);
    let len = n.length();
    if len < 1e-12 {
        Vec3::new(0.0, 0.0, -1.0)
    } else {
        n * (1.0 / len)
    }
}

/// One connected patch of overhanging surface.
pub struct Region {
    pub tris: Vec<u32>,
    pub area: f32,
    /// Lowest point of the patch: where a support is most needed.
    pub lowest: Vec3,
    /// Edges on the rim of the patch, sampled more densely for tips.
    pub rim: Vec<(Vec3, Vec3)>,
}

/// A piece of the model with nothing underneath it in the layer below.
pub struct Island {
    pub pos: Vec3,
    /// Footprint in mm².
    pub area: f32,
}

pub struct Detection {
    pub overhang: Vec<u32>,
    pub regions: Vec<Region>,
    pub islands: Vec<Island>,
    /// Faces flagged as overhang, as a mesh for the debug view.
    pub debug_mesh: Mesh,
}

/// The whole of stage 1.
pub fn detect(
    faces: &Faces,
    _meshes: &[Mesh],
    cfg: &SupportConfig,
    cancel: &AtomicBool,
) -> Detection {
    let limit = if cfg.overhangs_only {
        -cfg.overhang_angle_deg.to_radians().sin()
    } else {
        // "Overhangs Only" unchecked: every face that points down counts,
        // shallow slopes and flat undersides included.
        -1e-4
    };
    let overhang: Vec<u32> = (0..faces.len() as u32)
        .into_par_iter()
        .filter(|i| {
            let tri = faces.tris[*i as usize];
            // A downward-facing bottom face that is already on the build
            // platform does not need a support underneath it.
            let on_platform = tri.iter().all(|p| p.z <= 0.01);
            faces.normals[*i as usize].z <= limit + 1e-4 && !on_platform
        })
        .collect();

    let regions = group_regions(faces, &overhang, cancel);
    // Island topology is generated by the Prusa-style linked-layer analysis;
    // this stage is only responsible for the overhang debug mesh.
    let islands = Vec::new();

    let mut debug_mesh = Mesh::default();
    for i in &overhang {
        let t = faces.tris[*i as usize];
        let base = debug_mesh.verts.len() as u32;
        debug_mesh.verts.extend_from_slice(&t);
        debug_mesh.tris.push([base, base + 1, base + 2]);
    }

    Detection {
        overhang,
        regions,
        islands,
        debug_mesh,
    }
}

/// Group flagged faces into connected patches (sharing a welded corner).
fn group_regions(faces: &Faces, overhang: &[u32], cancel: &AtomicBool) -> Vec<Region> {
    if overhang.is_empty() {
        return Vec::new();
    }
    let mut dsu = Dsu::new(faces.len());
    let mut owner: HashMap<u32, u32> = HashMap::new();
    for &f in overhang {
        if cancel.load(Ordering::Relaxed) {
            return Vec::new();
        }
        for v in faces.ids[f as usize] {
            match owner.get(&v) {
                Some(&other) => dsu.union(f as usize, other as usize),
                None => {
                    owner.insert(v, f);
                }
            }
        }
    }
    let mut groups: HashMap<usize, Vec<u32>> = HashMap::new();
    for &f in overhang {
        let root = dsu.find(f as usize);
        groups.entry(root).or_default().push(f);
    }
    // a hash map hands its entries back in a different order each run, and the
    // tips would then be placed in a different order: sort to stay repeatable
    let mut grouped: Vec<(usize, Vec<u32>)> = groups.into_iter().collect();
    grouped.sort_by_key(|(root, _)| *root);

    let mut regions = Vec::new();
    for (_, tris) in grouped {
        let mut area = 0.0;
        let mut lowest = Vec3::new(0.0, 0.0, f32::MAX);
        let mut set: HashMap<(u32, u32), u32> = HashMap::new();
        for &t in &tris {
            area += faces.areas[t as usize];
            let c = faces.centroid(t);
            if c.z < lowest.z {
                lowest = c;
            }
            let v = faces.ids[t as usize];
            for (a, b) in [(v[0], v[1]), (v[1], v[2]), (v[2], v[0])] {
                let key = if a < b { (a, b) } else { (b, a) };
                *set.entry(key).or_insert(0) += 1;
            }
        }
        // An edge used once is on the rim: that is where tips go closer
        // together, because the surface stops there.
        let mut rim = Vec::new();
        let mut rim_keys: Vec<((u32, u32), u32)> = set.into_iter().collect();
        rim_keys.sort_by_key(|(k, _)| *k);
        for ((a, b), count) in rim_keys {
            if count == 1 {
                rim.push((faces.verts[a as usize], faces.verts[b as usize]));
            }
        }
        regions.push(Region {
            tris,
            area,
            lowest,
            rim,
        });
    }
    regions.sort_by(|a, b| {
        b.area
            .partial_cmp(&a.area)
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    regions
}

/// Islands: compare each slice with the one below, slightly grown.
pub fn find_islands(meshes: &[Mesh], step: f32, cell: f32, cancel: &AtomicBool) -> Vec<Island> {
    if meshes.is_empty() {
        return Vec::new();
    }
    let mut min = Vec3::new(f32::MAX, f32::MAX, 0.0);
    let mut max = Vec3::new(f32::MIN, f32::MIN, 0.0);
    for m in meshes {
        if m.tris.is_empty() {
            continue;
        }
        let (a, b) = m.bounds();
        min.x = min.x.min(a.x);
        min.y = min.y.min(a.y);
        max.x = max.x.max(b.x);
        max.y = max.y.max(b.y);
    }
    if min.x > max.x || min.y > max.y {
        return Vec::new();
    }
    let pad = cell * 2.0;
    let x0 = min.x - pad;
    let y0 = min.y - pad;
    let span_x = (max.x - min.x) + pad * 2.0;
    let span_y = (max.y - min.y) + pad * 2.0;
    // keep the grid affordable whatever the model's size
    let cell = cell.max(span_x / 400.0).max(span_y / 400.0);
    let w = ((span_x / cell).ceil() as usize).clamp(1, 420);
    let h = ((span_y / cell).ceil() as usize).clamp(1, 420);

    let sl = slicer::slice(meshes, step);
    let mut prev: Vec<bool> = vec![false; w * h];
    let mut islands = Vec::new();
    for layer in &sl.layers {
        if cancel.load(Ordering::Relaxed) {
            break;
        }
        let occ = slicer::occupancy(layer, [x0, y0], [x0 + span_x, y0 + span_y], w, h);
        // Material in the first layer is already attached to the build
        // platform. Seed the previous layer without reporting it as an
        // island, so the "on plate" setting does not grow supports below the
        // model.
        if layer.z <= step * 1.5 {
            prev = occ;
            continue;
        }
        // grown version of the layer below
        let mut new_cells: Vec<bool> = vec![false; w * h];
        for y in 0..h {
            for x in 0..w {
                if !occ[y * w + x] {
                    continue;
                }
                let mut covered = false;
                'grow: for dy in -1i32..=1 {
                    for dx in -1i32..=1 {
                        let nx = x as i32 + dx;
                        let ny = y as i32 + dy;
                        if nx < 0 || ny < 0 || nx >= w as i32 || ny >= h as i32 {
                            continue;
                        }
                        if prev[ny as usize * w + nx as usize] {
                            covered = true;
                            break 'grow;
                        }
                    }
                }
                if !covered {
                    new_cells[y * w + x] = true;
                }
            }
        }
        // connected groups of new cells, each becomes one island tip
        let mut seen = vec![false; w * h];
        for y in 0..h {
            for x in 0..w {
                let idx = y * w + x;
                if !new_cells[idx] || seen[idx] {
                    continue;
                }
                let mut stack = vec![(x, y)];
                seen[idx] = true;
                let mut sx = 0.0;
                let mut sy = 0.0;
                let mut n = 0usize;
                while let Some((cx, cy)) = stack.pop() {
                    sx += cx as f32 + 0.5;
                    sy += cy as f32 + 0.5;
                    n += 1;
                    for (dx, dy) in [(1i32, 0i32), (-1, 0), (0, 1), (0, -1)] {
                        let nx = cx as i32 + dx;
                        let ny = cy as i32 + dy;
                        if nx < 0 || ny < 0 || nx >= w as i32 || ny >= h as i32 {
                            continue;
                        }
                        let ni = ny as usize * w + nx as usize;
                        if new_cells[ni] && !seen[ni] {
                            seen[ni] = true;
                            stack.push((nx as usize, ny as usize));
                        }
                    }
                }
                if n == 0 {
                    continue;
                }
                islands.push(Island {
                    pos: Vec3::new(
                        x0 + sx / n as f32 * cell,
                        y0 + sy / n as f32 * cell,
                        layer.z,
                    ),
                    area: n as f32 * cell * cell,
                });
            }
        }
        prev = occ;
    }
    islands
}

// ------------------------------------------------------------- tiny union-find

struct Dsu {
    parent: Vec<u32>,
}

impl Dsu {
    fn new(n: usize) -> Self {
        Self {
            parent: (0..n as u32).collect(),
        }
    }
    fn find(&mut self, mut i: usize) -> usize {
        while self.parent[i] as usize != i {
            let p = self.parent[i] as usize;
            self.parent[i] = self.parent[p];
            i = p;
        }
        i
    }
    fn union(&mut self, a: usize, b: usize) {
        let ra = self.find(a);
        let rb = self.find(b);
        if ra != rb {
            self.parent[ra] = rb as u32;
        }
    }
}
